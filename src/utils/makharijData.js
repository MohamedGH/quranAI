/**
 * Pure helper retrieving anatomical data for a given letter.
 */
export const getLetterAnatomy = (letterChar) => {
  if (!letterChar) return null;
  return DETAILED_ARABIC_LETTERS.find((l) => l.letter === letterChar) || null;
};

/**
 * Pure helper retrieving child tip for a given letter.
 */
export const getLetterChildTip = (letterChar) => {
  const item = getLetterAnatomy(letterChar);
  return item?.childTip || item?.howToPronounce || "";
};

/**
 * Pure predicate checking whether a letter is one of the 7 heavy letters.
 */
export const isHeavyLetter = (letterChar) => {
  if (!letterChar) return false;
  return ["خ", "ص", "ض", "غ", "ط", "ق", "ظ"].includes(letterChar);
};

/**
 * Pure predicate checking whether a letter is one of the 4 Itbaq letters (highest heaviness).
 */
export const isItbaqLetter = (letterChar) => {
  if (!letterChar) return false;
  return HEAVY_LETTERS_DATA.itbaqLetters.includes(letterChar);
};

